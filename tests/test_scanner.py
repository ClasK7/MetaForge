import unittest

from metaforge.scanner import ForensicScanner, UNICODE_FINDING_TAG, is_tag_editable


class TestEditabilityPolicy(unittest.TestCase):
    def test_office_blocks_zip_modify_date_and_readonly_xml(self):
        self.assertFalse(is_tag_editable("doc.docx", "ZIP:ModifyDate", "2026:01:01 00:00:00"))
        self.assertFalse(is_tag_editable("doc.docx", "XML:Words", 500))
        self.assertFalse(is_tag_editable("doc.docx", "XML:HeadingPairs", ["Title", 1]))
        self.assertTrue(is_tag_editable("doc.docx", "XML:ModifyDate", "2026:01:01 00:00:00"))
        self.assertTrue(is_tag_editable("doc.docx", "XMP:Creator", "Ana"))
        self.assertTrue(is_tag_editable("doc.docx", "Company", "Acme"))

    def test_non_office_blocks_readonly_groups_jumbf_binary_and_composite(self):
        self.assertFalse(is_tag_editable("foto.jpg", "File:FileSize", "12 kB"))
        self.assertFalse(is_tag_editable("foto.jpg", "JUMBF:C2PAAssertion", "data"))
        self.assertFalse(is_tag_editable("foto.jpg", "EXIF:ThumbnailImage", "(Binary data 4321 bytes)"))
        self.assertFalse(is_tag_editable("foto.jpg", "XMP:Subject", ["a", "b"]))
        self.assertFalse(is_tag_editable("foto.jpg", "SourceFile", "foto.jpg"))
        self.assertTrue(is_tag_editable("foto.jpg", "EXIF:Artist", "Ana"))
        self.assertTrue(is_tag_editable("doc.pdf", "PDF:Author", "Ana"))


class TestForensicScanner(unittest.TestCase):
    def test_no_false_positives_on_common_photos_spanish_words_and_office_suites(self):
        metadata = {
            "SourceFile": "foto.jpg",
            "EXIF:ThumbnailImage": "(Binary data 4000 bytes)",
            "EXIF:ThumbnailOffset": 512,
            "EXIF:GainControl": "None",
            "XMP:Detail": "Normal",
            "EXIF:PortraitMode": "Off",
            "XML:HeadingPairs": ["Pages", 2],
            "XMP:Description": "Esta es una imagen tomada con LibreOffice y Google Docs y Canva",
            "XML:Application": "LibreOffice/7.6",
        }
        findings, flagged = ForensicScanner.analyze(metadata, {}, "foto.jpg")
        ai_findings = [f for f in findings if f["severity"] == "ai_high"]
        self.assertEqual(ai_findings, [])
        self.assertNotIn("EXIF:ThumbnailImage", flagged)

    def test_detects_real_ai_c2pa_and_opsec_simultaneously(self):
        metadata = {
            "PNG:Parameters": "masterpiece, Steps: 30, Sampler: Euler a, CFG scale: 7",
            "JUMBF:C2PAManifest": "TrainedAlgorithmicMedia",
            "XMP:Creator": "Generated by OpenAI ChatGPT",
            "EXIF:GPSLatitude": "40 deg 25' 0.00\" N",
        }
        findings, flagged = ForensicScanner.analyze(metadata, {"Zero-Width Space (U+200B)": 2}, "img.png")
        severities_by_tag = {}
        for f in findings:
            severities_by_tag.setdefault(f["tag"], set()).add(f["severity"])

        self.assertIn("ai_high", severities_by_tag["PNG:Parameters"])
        self.assertIn("ai_high", severities_by_tag["JUMBF:C2PAManifest"])
        # XMP:Creator dispara tanto ai_high como opsec_low sin ocultarse mutuamente
        self.assertEqual(severities_by_tag["XMP:Creator"], {"ai_high", "opsec_low"})
        self.assertEqual(flagged["XMP:Creator"], "ai_high")
        self.assertIn("opsec_low", severities_by_tag["EXIF:GPSLatitude"])
        self.assertIn("ai_high", severities_by_tag[UNICODE_FINDING_TAG])

    def test_automated_exporters_classified_as_anomaly_med(self):
        metadata = {"XML:Application": "python-docx", "PDF:Producer": "ReportLab PDF Library"}
        findings, _ = ForensicScanner.analyze(metadata, {}, "doc.pdf")
        self.assertTrue(all(f["severity"] == "anomaly_med" for f in findings))
        self.assertIn("ReportLab", findings[1]["reason"])

    def test_heuristics_edit_time_dates_heading_pairs_and_list_creator(self):
        # 1 hour NO debe marcarse como <= 2 minutos
        meta_ok_time = {"XML:Words": 500, "XML:TotalEditTime": "1 hour", "XML:RevisionNumber": 3}
        findings_ok, _ = ForensicScanner.analyze(meta_ok_time, {}, "doc.docx")
        self.assertEqual(findings_ok, [])

        # Fechas invertidas con mezcla naive y aware + HeadingPairs str + XMP:Creator como list
        meta_anom = {
            "XML:Words": 400,
            "XML:TotalEditTime": "1 minute",
            "XML:RevisionNumber": 1,
            "XML:CreateDate": "2026:05:10 12:00:00Z",
            "XML:ModifyDate": "2026:05:09 12:00:00",
            "PDF:CreateDate": "2020:01:01 00:00:00Z",  # Grupo distinto, no debe cruzarse con XML
            "XML:HeadingPairs": "Título 1 Title 1",
            "XMP:Creator": ["Ana"],
            "XML:LastModifiedBy": "Luis",
        }
        findings, _ = ForensicScanner.analyze(meta_anom, {}, "doc.docx")
        tags = {f["tag"] for f in findings}
        self.assertIn("XML:TotalEditTime", tags)
        self.assertIn("XML:RevisionNumber", tags)
        self.assertIn("XML:ModifyDate", tags)
        self.assertNotIn("PDF:CreateDate", tags)
        self.assertIn("XML:HeadingPairs", tags)
        self.assertIn("XMP:Creator", tags)


if __name__ == "__main__":
    unittest.main()
